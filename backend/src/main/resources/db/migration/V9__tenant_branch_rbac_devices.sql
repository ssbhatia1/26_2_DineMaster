CREATE TABLE user_branches (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, branch_id)
);
CREATE INDEX ix_user_branches_branch ON user_branches(branch_id, user_id);

-- Existing installations had no branch assignment model; preserve their current access.
