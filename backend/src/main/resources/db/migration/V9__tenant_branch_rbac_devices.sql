CREATE TABLE auth_devices (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tenant_id BIGINT REFERENCES tenants(id),
    label VARCHAR(100) NOT NULL DEFAULT 'Unknown device',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ
);
CREATE INDEX ix_auth_devices_user_active ON auth_devices(user_id, active);

ALTER TABLE auth_refresh_tokens ADD COLUMN device_id UUID REFERENCES auth_devices(id) ON DELETE SET NULL;

