
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    table_id BIGINT REFERENCES tables(id),
    customer_id BIGINT REFERENCES customers(id),
    waiter_id BIGINT REFERENCES users(id),
    restaurant_id BIGINT REFERENCES restaurants(id),

    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (total_amount >= 0),

    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (discount_amount >= 0),

    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    type VARCHAR(30) NOT NULL DEFAULT 'Dine In',

    order_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,

    payment_status VARCHAR(30) NOT NULL DEFAULT 'Unpaid',
    payment_method VARCHAR(50),

    customer_name VARCHAR(150),
    customer_phone VARCHAR(30),
    order_taker VARCHAR(150),
    delivered_by VARCHAR(150),
    delivery_timestamp TIMESTAMPTZ,
    guest_count INTEGER CHECK (guest_count IS NULL OR guest_count > 0)
);

CREATE INDEX idx_orders_restaurant_id
    ON orders(restaurant_id);

CREATE INDEX idx_orders_order_time
    ON orders(order_time);

CREATE INDEX idx_orders_status
    ON orders(status);


CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id BIGINT NOT NULL
        REFERENCES orders(id) ON DELETE CASCADE,

    product_id BIGINT NOT NULL
        REFERENCES products(id),

    quantity INTEGER NOT NULL CHECK (quantity > 0),

    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),

    notes TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'Pending'
);

CREATE INDEX idx_order_items_order_id
    ON order_items(order_id);

CREATE INDEX idx_order_items_product_id
    ON order_items(product_id);
