CREATE TABLE inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(150) NOT NULL,
    current_stock NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
    unit VARCHAR(30) NOT NULL,
    low_stock_threshold NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (low_stock_threshold >= 0),
    expiry_date DATE,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id)
);

CREATE INDEX idx_inventory_restaurant_id ON inventory(restaurant_id);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id BIGINT NOT NULL REFERENCES tables(id),
    customer_id BIGINT REFERENCES customers(id),
    customer_name VARCHAR(150),
    customer_phone VARCHAR(30),
    guest_count INTEGER NOT NULL CHECK (guest_count > 0),
    booking_time TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    notes TEXT,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id)
);

CREATE INDEX idx_bookings_restaurant_time ON bookings(restaurant_id, booking_time);