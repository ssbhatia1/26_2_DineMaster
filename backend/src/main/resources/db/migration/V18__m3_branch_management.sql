CREATE UNIQUE INDEX ux_restaurants_tenant_code ON restaurants (tenant_id, code);
CREATE INDEX ix_restaurants_tenant_active ON restaurants (tenant_id, is_active)
    WHERE deleted_at IS NULL;

CREATE TABLE branch_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    weekday VARCHAR(10) NOT NULL CHECK (weekday IN
        ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY')),
    open_time TIME,
    close_time TIME,
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_branch_hours_times CHECK (
        (is_closed AND open_time IS NULL AND close_time IS NULL)
        OR (NOT is_closed AND open_time IS NOT NULL AND close_time IS NOT NULL)
    ),
    CONSTRAINT uq_branch_hours_weekday UNIQUE (branch_id, weekday)
);
