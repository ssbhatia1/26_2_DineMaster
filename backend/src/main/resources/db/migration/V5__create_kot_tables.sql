CREATE TABLE kot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    kot_number VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_cooking_at TIMESTAMPTZ,
    ready_at TIMESTAMPTZ,
    served_at TIMESTAMPTZ,
    delay_reason TEXT,
    chef_name VARCHAR(150),
    priority VARCHAR(30) NOT NULL DEFAULT 'Normal',
    estimated_time INTEGER NOT NULL DEFAULT 15 CHECK (estimated_time > 0)
);

ALTER TABLE order_items ADD COLUMN kot_id BIGINT REFERENCES kot(id);
CREATE INDEX idx_kot_order_id ON kot(order_id);