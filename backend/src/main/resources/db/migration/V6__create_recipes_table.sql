CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES inventory(id),
    quantity_used NUMERIC(12, 3) NOT NULL CHECK (quantity_used > 0),
    CONSTRAINT recipes_product_ingredient_unique UNIQUE (product_id, ingredient_id)
);

CREATE INDEX idx_recipes_product_id ON recipes(product_id);