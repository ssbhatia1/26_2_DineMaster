
CREATE TABLE restaurants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address TEXT,
    phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    contact_details VARCHAR(255),
    shift_timing VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(255),
    loyalty_points INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100),
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    status VARCHAR(30) NOT NULL DEFAULT 'Available',
    section VARCHAR(100) NOT NULL DEFAULT 'Main Hall',
    table_type VARCHAR(50) NOT NULL DEFAULT 'Standard Table',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_reservable BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    waiter_id BIGINT REFERENCES users(id),
    restaurant_id BIGINT REFERENCES restaurants(id)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    restaurant_id BIGINT REFERENCES restaurants(id)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    ingredients TEXT,
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    category VARCHAR(100) NOT NULL,
    is_veg BOOLEAN NOT NULL,
    image_path TEXT,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    gst_percentage NUMERIC(5, 2) NOT NULL DEFAULT 5.00,
    dietary_preferences TEXT,
    taste_preferences TEXT,
    attributes TEXT,
    custom_dietary_notes TEXT,
    recipe_steps TEXT,
    prep_time INTEGER,
    cook_time INTEGER,
    servings INTEGER,
    difficulty VARCHAR(30),
    video_path TEXT,
    restaurant_id BIGINT REFERENCES restaurants(id)
);
