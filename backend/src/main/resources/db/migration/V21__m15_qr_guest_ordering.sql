CREATE TABLE table_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES restaurants(id),
    table_id BIGINT NOT NULL REFERENCES tables(id),
    token_hash CHAR(64) NOT NULL UNIQUE,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    CONSTRAINT ck_table_sessions_expiry CHECK (expires_at > opened_at)
);

ALTER TABLE orders
    ADD COLUMN channel VARCHAR(20) NOT NULL DEFAULT 'STAFF',
    ADD COLUMN table_session_id BIGINT REFERENCES table_sessions(id);

CREATE INDEX ix_table_sessions_table_open ON table_sessions(table_id, expires_at DESC)
    WHERE closed_at IS NULL;
CREATE INDEX ix_table_sessions_branch_open ON table_sessions(branch_id, opened_at DESC)
    WHERE closed_at IS NULL;

CREATE TABLE qr_order_idempotency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_sessions(id) ON DELETE CASCADE,
    idempotency_key VARCHAR(100) NOT NULL,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_qr_idempotency_session_key UNIQUE (session_id, idempotency_key)
);

CREATE TABLE guest_service_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_sessions(id) ON DELETE CASCADE,
    request_type VARCHAR(30) NOT NULL DEFAULT 'CALL_WAITER',
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    acknowledged_at TIMESTAMPTZ,
    CONSTRAINT ck_guest_service_request_type CHECK (request_type IN ('CALL_WAITER')),
    CONSTRAINT ck_guest_service_request_status CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'CANCELLED'))
);

CREATE INDEX ix_guest_service_requests_open ON guest_service_requests(session_id, created_at DESC)
    WHERE status = 'OPEN';
